/**
 * Writes the large feed fixtures that scripts/perf/run.ts serves: a 300-post Reddit feed, a
 * 1,500-comment Reddit thread, a 400-post X timeline with its HomeTimeline body and a 300-post
 * Bluesky feed. Every item copies the markup shape of the hand-written fixtures under
 * tests/fixtures/<platform>/html/, so the content scripts read them the same way. The generator is
 * seeded, so the output only changes when this file does.
 *
 *   pnpm perf:fixtures
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export const perfFixtureDir: URL = new URL("../../tests/fixtures/perf/", import.meta.url);
/** The X page fetches this; the interceptor accepts any query id of the right shape. */
export const perfHomeTimelinePath = "/i/api/graphql/PERFQUERYID000000001/HomeTimeline";
/** Account ages in the X body count back from this date, like the recorded fixtures. */
const RECORDING_DATE_MS: number = Date.parse("2026-10-22T12:00:00.000Z");
const DAY_MS = 86_400_000;
const MAX_COMMENT_DEPTH = 6;
const REDDIT_STOCK_AVATAR = "https://www.redditstatic.com/avatars/defaults/v2/avatar_default_3.png";
/** Reddit's registered-app tag as recorded: a bare "APP" leaf in the author row. */
const REDDIT_APP_TAG = `<span class="text-12 font-semibold uppercase">APP</span>`;
const X_STOCK_AVATAR =
  "https://abs.twimg.com/sticky/default_profile_images/default_profile_normal.png";

const adjectives: readonly string[] = ["Quiet", "Brisk", "Mossy", "Amber", "Lucky", "Rapid"];
const nouns: readonly string[] = ["Lantern", "Falcon", "Teapot", "Badger", "Willow", "Comet"];
const firstNames: readonly string[] = ["alice", "maria", "jonas", "priya", "tomas", "lena", "omar"];
const topics: readonly string[] = ["reads", "builds", "codes", "bakes", "runs", "draws", "sails"];
const subreddits: readonly string[] = ["woodworking", "dailydeals", "askscience", "cooking"];
const sentences: readonly string[] = [
  "The grain on that top is lovely. What finish did you use?",
  "Hardwax oil, two coats, then a light buff.",
  "Has anyone tried this with a cheaper router? Mine chatters at the edges.",
];

type Random = () => number;

/** mulberry32: small, seedable and good enough to spread names and flags. */
function seededRandom(seed: number): Random {
  let state: number = seed >>> 0;
  return (): number => {
    state = (state + 0x6d2b79f5) >>> 0;
    let mixed: number = Math.imul(state ^ (state >>> 15), 1 | state);
    mixed = (mixed + Math.imul(mixed ^ (mixed >>> 7), 61 | mixed)) ^ mixed;
    return ((mixed ^ (mixed >>> 14)) >>> 0) / 4_294_967_296;
  };
}

function pick<T>(random: Random, items: readonly T[]): T {
  return items[Math.floor(random() * items.length)] as T;
}

function digits(random: Random, length: number): string {
  return Array.from({ length }, () => Math.floor(random() * 10)).join("");
}

/** A chosen name most of the time, Reddit's suggested Adjective_Noun_1234 shape otherwise. */
function redditUsername(random: Random): string {
  return random() < 0.3
    ? `${pick(random, adjectives)}_${pick(random, nouns)}_${digits(random, 4)}`
    : `${pick(random, firstNames)}_${pick(random, topics)}${Math.floor(random() * 90) + 10}`;
}

function page(title: string, description: readonly string[], body: string, script = ""): string {
  const comment: string = description.map((line) => `\n  ${line}`).join("");
  return `<!doctype html>
<!--
  Generated by scripts/perf/generateFixtures.ts (pnpm perf:fixtures); do not edit by hand.${comment}
-->
<html lang="en" data-theme="light">
  <head>
    <meta charset="utf-8" />
    <title>${title}</title>
  </head>
  <body>
${body}
${script}
  </body>
</html>
`;
}

// MARK: - Reddit

function redditAuthorLink(name: string, avatar: string | undefined): string {
  const image: string =
    avatar === undefined ? "" : `<img src="${avatar}" alt="u/${name} avatar" />`;
  const link = `<a href="/user/${name}/" class="author-name">${image}u/${name}</a>`;
  return `<faceplate-hovercard aria-label="User info">${link}</faceplate-hovercard>`;
}

/**
 * One shreddit-post in either shape of tests/fixtures/reddit/html/feed.html: the credit bar slotted
 * into light DOM, or the author row only inside the declarative shadow root, which is always the
 * shape for an APP-tagged author, as recorded.
 */
function redditPost(random: Random, index: number, appTagged: boolean): string {
  const name: string = redditUsername(random);
  const subreddit: string = pick(random, subreddits);
  const id = `t3_perf${index.toString(36).padStart(4, "0")}`;
  const permalink = `/r/${subreddit}/comments/${id.slice(3)}/post_${index}/`;
  const avatarRoll: number = random();
  const avatar: string | undefined =
    avatarRoll < 0.5 ? undefined : avatarRoll < 0.65 ? REDDIT_STOCK_AVATAR : `/icons/${index}.png`;
  const community = `<a href="/r/${subreddit}/"><span class="font-bold">r/${subreddit}</span></a>`;
  const meta = `${community}<span>by</span>${redditAuthorLink(name, avatar)}`;
  const inShadow: boolean = appTagged || random() < 0.5;
  const authorRow: string = inShadow
    ? `<div class="credit-bar flex items-center">${meta}${appTagged ? REDDIT_APP_TAG : ""}</div>`
    : `<slot name="credit-bar"></slot>`;
  return [
    `<article class="w-full m-0"><shreddit-post id="${id}" author="${name}"`,
    ` author-id="t2_${index}" created-timestamp="2026-10-21T09:41:00.000+0000"`,
    ` subreddit-prefixed-name="r/${subreddit}" post-title="Post ${index}" permalink="${permalink}"`,
    ` post-type="link" score="${Math.floor(random() * 500)}" comment-count="${index % 80}">`,
    `<template shadowrootmode="open"><div class="post-container">${authorRow}`,
    `<slot name="title"></slot><slot name="post-footer"></slot></div></template>`,
    inShadow ? "" : `<div slot="credit-bar" class="flex items-center">${meta}</div>`,
    `<a slot="title" href="${permalink}">Post ${index}: ${pick(random, sentences)}</a>`,
    `<div slot="post-footer"></div></shreddit-post></article>`,
  ].join("");
}

/** Markup for `count` feed posts, every tenth APP-tagged; the runner reuses it for live insertion. */
export function redditFeedPosts(count: number, seed: number, firstIndex = 0): string {
  const random: Random = seededRandom(seed);
  return Array.from({ length: count }, (_, offset) => {
    const index: number = firstIndex + offset;
    return redditPost(random, index, index % 10 === 3);
  }).join("\n");
}

interface CommentNode {
  readonly depth: number;
  readonly children: CommentNode[];
}

/** Each comment replies to a random comment that can still nest, or starts a new top-level one. */
function commentForest(random: Random, count: number): CommentNode[] {
  const roots: CommentNode[] = [];
  const nestable: CommentNode[] = [];
  for (let created = 0; created < count; created += 1) {
    const parent: CommentNode | undefined =
      random() < 0.8 ? nestable[Math.floor(random() * nestable.length)] : undefined;
    const node: CommentNode = { depth: parent === undefined ? 0 : parent.depth + 1, children: [] };
    (parent?.children ?? roots).push(node);
    if (node.depth < MAX_COMMENT_DEPTH) nestable.push(node);
  }
  return roots;
}

function redditComment(
  random: Random,
  node: CommentNode,
  ids: { next: number },
  parentId: string,
): string {
  const name: string = redditUsername(random);
  const appTagged: boolean = ids.next % 50 === 17;
  const id = `t1_perf${(ids.next++).toString(36).padStart(4, "0")}`;
  const avatar: string | undefined = random() < 0.4 ? REDDIT_STOCK_AVATAR : undefined;
  const slots: string = ["commentMeta", "comment", "actionRow", "children"]
    .map((slot) => `<slot name="${slot}"></slot>`)
    .join("");
  return [
    `<shreddit-comment${node.depth === 0 ? "" : ` slot="children"`} author="${name}" thingid="${id}"`,
    ` postid="t3_perfthread" parentid="${parentId}" depth="${node.depth}" score="${ids.next % 60}">`,
    `<template shadowrootmode="open"><div class="comment">${slots}</div></template>`,
    `<div slot="commentMeta" class="flex items-center">${redditAuthorLink(name, avatar)}`,
    appTagged ? REDDIT_APP_TAG : "",
    `<faceplate-timeago ts="2026-10-21T02:05:00.000+0000">1 day ago</faceplate-timeago></div>`,
    `<div slot="comment"><p>${pick(random, sentences)}</p></div>`,
    ...node.children.map((child) => redditComment(random, child, ids, id)),
    `</shreddit-comment>`,
  ].join("");
}

function redditCommentsPage(count: number): string {
  const random: Random = seededRandom(count);
  const ids = { next: 0 };
  const comments: string = commentForest(random, count)
    .map((root) => redditComment(random, root, ids, ""))
    .join("\n");
  const post: string = redditFeedPosts(1, 99, 9_000).replace(/^<article[^>]*>|<\/article>$/g, "");
  return page(
    "reddit",
    [
      `One post and ${count} shreddit-comment items nested up to depth ${MAX_COMMENT_DEPTH}, in the`,
      "shape of tests/fixtures/reddit/html/comments.html; every 50th carries the APP tag.",
    ],
    `<shreddit-app>${post}<shreddit-comment-tree id="comment-tree">\n${comments}\n</shreddit-comment-tree></shreddit-app>`,
  );
}

// MARK: - X

interface XAuthor {
  readonly handle: string;
  readonly name: string;
  readonly automated: boolean;
  readonly likelyBot: boolean;
  readonly avatar: string;
}

function xAuthor(random: Random, index: number): XAuthor {
  const likelyBot: boolean = index % 20 === 13;
  const automated: boolean = index % 20 === 7;
  const first: string = pick(random, firstNames);
  return {
    handle: likelyBot ? `${first}${digits(random, 8)}` : `${first}_${pick(random, topics)}${index}`,
    name: `${first.charAt(0).toUpperCase()}${first.slice(1)}`,
    automated,
    likelyBot,
    avatar: automated || likelyBot ? X_STOCK_AVATAR : `https://pbs.twimg.com/${index}_normal.jpg`,
  };
}

/** The article shape of tests/fixtures/x/html/timeline.html; the Automated and reply rows are optional. */
function xArticle(random: Random, author: XAuthor): string {
  const span = (text: string): string =>
    `<span class="css-1jxf684 r-bcqeeo r-poiln3">${text}</span>`;
  const profileLink = (inner: string): string =>
    `<a href="/${author.handle}" role="link">${inner}</a>`;
  const div = (...children: string[]): string =>
    `<div class="css-175oi2r">${children.join("")}</div>`;
  const repliedTo = `<a href="/alice_reads1" role="link">${span("@alice_reads1")}</a>`;
  return [
    `<div data-testid="cellInnerDiv"><article data-testid="tweet" role="article" tabindex="0">`,
    div(
      div(
        `<div data-testid="Tweet-User-Avatar">`,
        div(profileLink(`<img alt="" src="${author.avatar}" />`)),
        `</div>`,
      ),
      div(
        div(
          div(
            `<div data-testid="User-Name" class="css-175oi2r">`,
            div(div(profileLink(`<div dir="ltr">${span(span(author.name))}</div>`))),
            div(
              div(profileLink(`<div dir="ltr">${span(`@${author.handle}`)}</div>`)),
              `<div dir="ltr" aria-hidden="true">${span("·")}</div>`,
              div(profileLink(`<time datetime="2026-10-22T08:10:00.000Z">2h</time>`)),
            ),
            author.automated ? div(span("Automated")) : "",
            `</div>`,
          ),
        ),
        random() < 0.1 ? div(`<div dir="ltr">${span("Replying to ")}${repliedTo}</div>`) : "",
        div(
          `<div data-testid="tweetText" dir="auto" lang="en">${span(pick(random, sentences))}</div>`,
        ),
      ),
    ),
    `</article></div>`,
  ].join("");
}

/** A user object in the shape of tests/fixtures/x/graphql/home-timeline-core.json. */
function xUser(author: XAuthor, index: number): Record<string, unknown> {
  const ageDays: number = author.likelyBot ? 10 : 400 + index * 7;
  const stockAvatar: boolean = author.avatar === X_STOCK_AVATAR;
  return {
    __typename: "User",
    rest_id: `1${String(index).padStart(18, "0")}`,
    affiliates_highlighted_label: author.automated
      ? { label: { userLabelType: "AutomatedLabel", description: "Automated" } }
      : {},
    avatar: { image_url: author.avatar },
    core: {
      created_at: new Date(RECORDING_DATE_MS - ageDays * DAY_MS).toISOString(),
      name: author.name,
      screen_name: author.handle,
    },
    is_blue_verified: false,
    legacy: { default_profile: stockAvatar, default_profile_image: stockAvatar },
    profile_bio: { description: author.likelyBot ? "" : "Opinions are my own." },
    relationship_counts: author.likelyBot
      ? { followers: 12, following: 4900 }
      : { followers: 340 + index, following: 210 },
    tweet_counts: { tweets: author.likelyBot ? 1500 : 4100, media_tweets: 40 },
    verification: { verified: false },
  };
}

function xTimeline(count: number, bodyFile: string): { html: string; body: string } {
  const random: Random = seededRandom(count);
  const authors: XAuthor[] = Array.from({ length: count }, (_, index) => xAuthor(random, index));
  const articles: string = authors.map((author) => xArticle(random, author)).join("\n");
  const entries = authors.map((author, index) => {
    const tweet = { __typename: "Tweet", core: { user_results: { result: xUser(author, index) } } };
    const itemContent = { itemType: "TimelineTweet", tweet_results: { result: tweet } };
    return {
      entryId: `tweet-${index}`,
      content: { entryType: "TimelineTimelineItem", itemContent },
    };
  });
  const instructions = [{ type: "TimelineAddEntries", entries }];
  const script = `    <script>
      // Fetches the HomeTimeline body like the web app does, so the MAIN-world interceptor relays it
      // to Tier 1; repeated because the content script only subscribes at document_idle.
      window.addEventListener("load", () => {
        for (const delay of [0, 500, 1500]) {
          setTimeout(() => fetch("${perfHomeTimelinePath}").catch(() => undefined), delay);
        }
      });
    </script>`;
  const html: string = page(
    "Home / X",
    [
      `${count} article[data-testid="tweet"] cells in the shape of tests/fixtures/x/html/timeline.html.`,
      "Authors 7, 27, 47, ... carry the Automated label; authors 13, 33, 53, ... are ten-day-old",
      `name-plus-digits accounts whose counts in ${bodyFile} score Likely bot.`,
    ],
    `<div id="react-root"><main role="main"><div aria-label="Timeline: Your Home Timeline">\n${articles}\n</div></main></div>`,
    script,
  );
  return {
    html,
    body: `${JSON.stringify({ data: { home: { home_timeline_urt: { instructions } } } })}\n`,
  };
}

// MARK: - Bluesky

function blueskyPost(random: Random, index: number): string {
  const declared: boolean = index % 20 === 5;
  const handle = `${pick(random, firstNames)}${index}.bsky.social`;
  const profileLink = (inner: string): string => `<a href="/profile/${handle}">${inner}</a>`;
  return [
    `<div data-testid="feedItem-by-${handle}"><div class="post-header">`,
    profileLink(
      declared
        ? `<div data-testid="userAvatarFallback"><svg viewBox="0 0 24 24"></svg></div>`
        : `<img data-testid="userAvatarImage" src="https://cdn.example/avatar/${index}.jpg" alt="" />`,
    ),
    `<div class="author-row">`,
    profileLink(
      `<span>Poster ${index}</span>${declared ? `<span data-testid="botBadge" aria-label="Bot account"></span>` : ""}`,
    ),
    profileLink(`<span>@${handle}</span>`),
    `<span>&middot; 2h</span></div></div>`,
    `<div class="post-body">${pick(random, sentences)}</div></div>`,
  ].join("");
}

// MARK: - Main

function writeFixture(name: string, contents: string): void {
  writeFileSync(new URL(name, perfFixtureDir), contents);
  process.stdout.write(
    `wrote tests/fixtures/perf/${name} (${Math.round(contents.length / 1024)} KiB)\n`,
  );
}

function main(): void {
  mkdirSync(perfFixtureDir, { recursive: true });
  writeFixture(
    "reddit-feed-300.html",
    page(
      "reddit",
      [
        "300 shreddit-post items in the shapes of tests/fixtures/reddit/html/feed.html; every tenth",
        "carries the APP tag.",
      ],
      `<shreddit-app><shreddit-feed id="main-feed">\n${redditFeedPosts(300, 300)}\n</shreddit-feed></shreddit-app>`,
    ),
  );
  writeFixture("reddit-comments-1500.html", redditCommentsPage(1500));
  const timeline = xTimeline(400, "x-home-timeline-400.json");
  writeFixture("x-timeline-400.html", timeline.html);
  writeFixture("x-home-timeline-400.json", timeline.body);
  const random: Random = seededRandom(300);
  writeFixture(
    "bluesky-feed-300.html",
    page(
      "Bluesky",
      [
        "300 feed items in the shape of tests/fixtures/bluesky/html/feed.html; every 20th carries",
        "Bluesky's robot badge. No API body is served, so only Tier 0 runs.",
      ],
      Array.from({ length: 300 }, (_, index) => blueskyPost(random, index)).join("\n"),
    ),
  );
}

const runAsScript: boolean =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (runAsScript) main();
